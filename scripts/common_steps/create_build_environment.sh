#!/bin/bash

# Exit immediately if a command fails.
set -e

# Check arguments.
if [ $# != 11 ]; then
  echo "Number of arguments is incorrect."
  echo "Usage: ./create_build_environment.sh SOURCE_DIR BUILD_DIR FROM_SOURCE C_COMPILER CXX_COMPILER BUILD_TYPE ENABLE_TESTS ENABLE_FORMAT ENABLE_TIDY UNITS_IMPLEMENTATION VALUE_MATRIX_IMPLEMENTATION"
  exit 1
fi

SOURCE_DIR=${1}
BUILD_DIR=${2}
FROM_SOURCE=${3}
C_COMPILER=${4}
CXX_COMPILER=${5}
BUILD_TYPE=${6}
ENABLE_TESTS=${7}
ENABLE_FORMAT=${8}
ENABLE_TIDY=${9}
UNITS_IMPLEMENTATION=${10}
VALUE_MATRIX_IMPLEMENTATION=${11}

# Create build environment.
cmake -E make_directory ${BUILD_DIR}
cmake -S ${SOURCE_DIR} -B ${BUILD_DIR} -D FROM_SOURCE=${FROM_SOURCE} -D CMAKE_C_COMPILER=${C_COMPILER} -D CMAKE_CXX_COMPILER=${CXX_COMPILER} -D CMAKE_BUILD_TYPE=${BUILD_TYPE} -D ENABLE_TESTS=${ENABLE_TESTS} -D ENABLE_FORMAT=${ENABLE_FORMAT} -D ENABLE_TIDY=${ENABLE_TIDY} -D UNITS_IMPLEMENTATION=${UNITS_IMPLEMENTATION} -D VALUE_MATRIX_IMPLEMENTATION=${VALUE_MATRIX_IMPLEMENTATION} -D CODE_COVERAGE=ON

exit 0
