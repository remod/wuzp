#!/bin/bash

# Exit immediately if a command fails.
set -e

# Check arguments.
if [ $# != 12 ]; then
  echo "Number of arguments is incorrect: $*"
  echo "Usage: ./create_build_environment.sh SOURCE_DIR BUILD_DIR FROM_SOURCE CMAKE_C_COMPILER CMAKE_CXX_COMPILER BUILD_TYPE ENABLE_TESTS ENABLE_CODE_COVERAGE ENABLE_FORMAT ENABLE_TIDY UNITS_IMPLEMENTATION VALUES_IMPLEMENTATION"
  exit 1
fi

SOURCE_DIR=${1}
BUILD_DIR=${2}
FROM_SOURCE=${3}
CMAKE_C_COMPILER=${4}
CMAKE_CXX_COMPILER=${5}
BUILD_TYPE=${6}
ENABLE_TESTS=${7}
ENABLE_CODE_COVERAGE=${8}
ENABLE_FORMAT=${9}
ENABLE_TIDY=${10}
UNITS_IMPLEMENTATION=${11}
VALUES_IMPLEMENTATION=${12}

# Create build environment.
cmake -E make_directory ${BUILD_DIR}
cmake -S ${SOURCE_DIR} -B ${BUILD_DIR} -D FROM_SOURCE=${FROM_SOURCE} -D CMAKE_C_COMPILER=${CMAKE_C_COMPILER} -D CMAKE_CXX_COMPILER=${CMAKE_CXX_COMPILER} -D CMAKE_BUILD_TYPE=${BUILD_TYPE} -D ENABLE_TESTS=${ENABLE_TESTS} -D ENABLE_CODE_COVERAGE=${ENABLE_CODE_COVERAGE} -D ENABLE_FORMAT=${ENABLE_FORMAT} -D ENABLE_TIDY=${ENABLE_TIDY} -D UNITS_IMPLEMENTATION=${UNITS_IMPLEMENTATION} -D VALUES_IMPLEMENTATION=${VALUES_IMPLEMENTATION}

exit 0
